#!/usr/bin/env python3
"""Build the translated `values-*` string resources from the tables beside this file.

Each language has a tab-separated table, `<tag>.tsv`, of `name<TAB>text`. The
English text and the list of names come from the app's own `values/strings.xml`,
so a key can never be invented here: an entry whose name is not in the English
file is reported and skipped, and an English string with no entry falls back to
English at runtime (which is what Android does for a missing translation).

The text is plain Unicode, not XML: `'`, `"`, `&` and `<` are escaped here, so
the tables stay readable and cannot produce a broken resource file. A `¶` is a
line break, written to the resource as `\\n`; a string with a bare `%` and no
positional argument is marked `formatted="false"` so aapt does not read it as a
format string.

Run from the repository root:

    python3 tools/i18n/build_strings.py          # write the resources
    python3 tools/i18n/build_strings.py --check  # report coverage, write nothing
"""
from __future__ import annotations

import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "android/app/src/main/res"
ENGLISH = RES / "values/strings.xml"
TABLES = Path(__file__).resolve().parent

# The tag in the table, and the resource qualifier it is written to. European
# Portuguese is `pt-rPT`, so a Brazilian `values-pt` from a library cannot be
# picked for it.
LANGUAGES = {
    "ar": "ar",
    "fr": "fr",
    "es": "es",
    "ru": "ru",
    "pt": "pt-rPT",
}

# Every name the English file defines, in file order.
HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/i18n/build_strings.py from tools/i18n/{tag}.tsv.
     Edit the table, not this file. -->
<resources>
"""


def english_strings() -> tuple[list[str], dict[str, str]]:
    tree = ET.parse(ENGLISH)
    names: list[str] = []
    texts: dict[str, str] = {}
    for element in tree.getroot().findall("string"):
        name = element.get("name")
        if not name:
            continue
        names.append(name)
        texts[name] = element.text or ""
    return names, texts


def read_table(tag: str) -> dict[str, str]:
    """A language's entries: `<tag>.tsv`, then any `<tag>-*.tsv` beside it.

    The split keeps one file readable; a later table may add keys but never
    silently override an earlier one.
    """
    paths = [TABLES / f"{tag}.tsv"] + sorted(TABLES.glob(f"{tag}-*.tsv"))
    table: dict[str, str] = {}
    for path in paths:
        if not path.exists():
            continue
        for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if not raw.strip() or raw.lstrip().startswith("#"):
                continue
            if "\t" not in raw:
                raise SystemExit(f"{path.name}:{number}: expected name<TAB>text")
            name, text = raw.split("\t", 1)
            name = name.strip()
            if name in table:
                raise SystemExit(f"{path.name}:{number}: {name} is given twice")
            table[name] = text.strip()
    return table


def escape(text: str) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("¶", "\\n")
    # Android reads a quote at the start of a value as the quote character that
    # keeps spaces; an apostrophe has to be escaped inside a resource.
    text = text.replace("'", "\\'").replace('"', '\\"')
    if text.startswith("@"):
        text = "\\" + text
    if text.startswith("?"):
        text = "\\" + text
    return text


def is_format(text: str) -> bool:
    return bool(re.search(r"%(?:\d+\$)?[a-zA-Z]", text))


ARGUMENT = re.compile(r"%(?:\d+\$)?[-#+0,(]*\d*(?:\.\d+)?[a-zA-Z]")


def arguments(text: str) -> list[str]:
    """The format arguments a string expects, in order, e.g. ['%1$s', '%2$d'].

    A translation that drops, adds or renumbers one would crash `getString` at
    runtime, or print a wrong value, so the build compares them with English.
    """
    return ARGUMENT.findall(text)


def build(tag: str, names: list[str], english: dict[str, str], table: dict[str, str]) -> str:
    unknown = sorted(set(table) - set(names))
    for name in unknown:
        print(f"  {tag}: {name} is not in values/strings.xml; skipped", file=sys.stderr)
    out = [HEADER.format(tag=tag)]
    for name in names:
        if name not in table:
            continue
        text = table[name]
        if not text:
            continue
        attribute = ""
        if "%" in text and not is_format(text):
            attribute = ' formatted="false"'
        out.append(f'    <string name="{name}"{attribute}>{escape(text)}</string>\n')
    out.append("</resources>\n")
    return "".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="report coverage, write nothing")
    args = parser.parse_args()

    names, english = english_strings()
    # Autonyms and pure formats are shown exactly as they are in English: every
    # language lists itself in its own script, and "3x" is "3x" everywhere.
    fixed = {n for n in names if n.startswith("language_name_")} | {
        "qg_scale_value", "qg_scene_value", "qg_fps_value",
    }
    translatable = [n for n in names if n not in fixed]
    problems = 0
    for tag, qualifier in LANGUAGES.items():
        table = read_table(tag)
        missing = [n for n in translatable if n not in table]
        coverage = 100.0 * (len(translatable) - len(missing)) / len(translatable)
        print(f"{tag:>2} -> values-{qualifier}: {len(translatable) - len(missing)}/{len(translatable)}"
              f" ({coverage:.1f}%)")
        if missing:
            problems += len(missing)
            print("   missing: " + ", ".join(missing[:12]) + (" ..." if len(missing) > 12 else ""))
        for name, text in table.items():
            if name not in english:
                continue
            want, got = arguments(english[name]), arguments(text)
            if sorted(want) != sorted(got):
                problems += 1
                print(f"   {name}: English has {want}, {tag} has {got}", file=sys.stderr)
        if not args.check:
            target = RES / f"values-{qualifier}"
            target.mkdir(parents=True, exist_ok=True)
            (target / "strings.xml").write_text(
                build(tag, names, english, table), encoding="utf-8",
            )
    return 0 if problems == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
